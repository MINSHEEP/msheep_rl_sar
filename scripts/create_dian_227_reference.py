"""Check the actual training/playback contract without pretending unfinished weights are trained."""
import argparse
import sys
from pathlib import Path
from types import SimpleNamespace

import mujoco
import numpy as np
import yaml

parser = argparse.ArgumentParser()
parser.add_argument('--reference-root', required=True, type=Path)
parser.add_argument('--output', required=True, type=Path)
parser.add_argument('--test-model', type=Path, help='Optional untrained zero-output graph for FSM tests only')
args = parser.parse_args()
sys.path.insert(0, str(args.reference_root / 'scripts/mujoco'))
import dian_stairs as reference

actor = SimpleNamespace(observation_size=227, motor_gains=(50., 1.),
                        action_filter=reference.ActionFilter((4., 8., 6.), .1, 1., .04, False, 0., 0.))
model = mujoco.MjModel.from_xml_string(reference.build_scene(terrain='flat', contact_profile='dian_sim2sim_v1'))
c = reference.Controller(model, actor)
# This profile must never ask the simulator for privileged contact/height data.
def forbidden(*args, **kwargs):
    raise AssertionError('227 contract unexpectedly requested privileged state')
c.contacts = c.support_height = c.terrain_heights = forbidden
frames = []
for step in range(90):
    command = np.array([.3, -.1, .2]) if step < 10 or step >= 75 else np.zeros(3)
    c.data.qpos[c.qadr] = reference.DEFAULT_POS + np.sin(np.arange(12) + step * .1) * .03
    c.data.qvel[c.vadr] = np.cos(np.arange(12) + step * .1) * .1
    mujoco.mj_forward(model, c.data)
    velocity = np.zeros(6)
    mujoco.mj_objectVelocity(model, c.data, mujoco.mjtObj.mjOBJ_BODY, c.base_id, velocity, 0)
    rotation = c.data.xmat[c.base_id].reshape(3, 3)
    obs = c.observation(command, update_history=True)
    action = (np.sin(np.arange(12) + step * .2) * 2).astype(np.float32)
    c.update_target(action, command)
    c.last_action[:] = action
    frames.append(dict(command=command.tolist(), q=c.data.qpos[c.qadr].tolist(), dq=c.data.qvel[c.vadr].tolist(),
                       gyro=(rotation.T @ velocity[:3]).tolist(), gravity=(rotation.T @ [0., 0., -1.]).tolist(),
                       observation=obs.tolist(), action=action.tolist(), target=c.target.tolist()))
    c.ticks += 4
args.output.write_text('# Generated by scripts/create_dian_227_reference.py; do not edit.\n' +
                       yaml.safe_dump(dict(frames=frames), default_flow_style=True, width=120))
print(f'Generated {len(frames)} frames from actual 227 observation/filter implementation; synthetic actions, no policy weights.')

if args.test_model:
    import onnx
    from onnx import helper, TensorProto
    graph = helper.make_graph(
        [helper.make_node('Constant', [], ['actions'], value=helper.make_tensor('zero', TensorProto.FLOAT, [1, 12], [0.] * 12))],
        'UNTRAINED_FSM_TEST_ONLY', [helper.make_tensor_value_info('obs', TensorProto.FLOAT, [1, 227])],
        [helper.make_tensor_value_info('actions', TensorProto.FLOAT, [1, 12])])
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid('', 17)], ir_version=8)
    onnx.checker.check_model(model)
    onnx.save(model, str(args.test_model))
